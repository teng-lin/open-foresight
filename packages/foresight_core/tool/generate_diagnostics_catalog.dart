// Development-only registry projection. Runtime diagnostics import neither the
// application Operation descriptors nor Store/native application bootstrap.
import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';

void main(List<String> arguments) {
  final root = Directory('lib');
  final operations =
      parseString(
        content: File('lib/src/operations.dart').readAsStringSync(),
      ).unit.declarations.whereType<EnumDeclaration>().singleWhere(
        (declaration) => declaration.namePart.typeName.lexeme == 'Operation',
      );
  final wires = operations.body.constants.map((constant) {
    final literal =
        constant.arguments!.argumentList.arguments.first as StringLiteral;
    return literal.stringValue!;
  }).toList();
  final paths =
      root
          .listSync(recursive: true, followLinks: false)
          .whereType<File>()
          .where((file) => file.path.endsWith('.dart'))
          .map((file) => file.path.substring(4))
          .toList()
        ..sort();
  final outputs = {
    'lib/src/diagnostics/operations.g.dart':
        '// Generated by tool/generate_diagnostics_catalog.dart.\n'
        'const diagnosticOperations = <String>{\n'
        '${wires.map((wire) => "  '$wire',\n").join()}'
        '};\n',
    'lib/src/diagnostics/code_locations.g.dart':
        '// Generated by tool/generate_diagnostics_catalog.dart.\n'
        'const diagnosticCodeLocations = <String>[\n'
        '${paths.map((path) => "  '$path',\n").join()}'
        '];\n',
  };
  for (final output in outputs.entries) {
    final file = File(output.key);
    if (arguments.contains('--check')) {
      if (!file.existsSync() || file.readAsStringSync() != output.value) {
        stderr.writeln(
          'Diagnostic catalog requires regeneration: ${output.key}',
        );
        exitCode = 1;
      }
    } else {
      file.writeAsStringSync(output.value);
    }
  }
}
