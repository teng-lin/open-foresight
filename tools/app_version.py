#!/usr/bin/env python3
"""Read, check, or set the Open Foresight version.

apps/desktop/pubspec.yaml is the single source of truth: `version: X.Y.Z+N`, where
X.Y.Z is the user-visible release version and N is a build number that only grows.
Every other copy is derived from it, either at build time (CMake, packaging) or
by `--set`, which rewrites the checked-in copies that tools cannot read at runtime.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PUBSPEC = 'apps/desktop/pubspec.yaml'
CORE_PUBSPEC = 'packages/foresight_core/pubspec.yaml'
DESKTOP_LOCK = 'apps/desktop/pubspec.lock'
DART_VERSION = 'packages/foresight_core/lib/src/version.dart'
COMPONENT = r'(?:0|[1-9][0-9]*)'
SEMVER = re.compile(rf'{COMPONENT}\.{COMPONENT}\.{COMPONENT}')
SOURCE = re.compile(rf'^version: ({SEMVER.pattern})\+({COMPONENT})$', re.M)
CORE_VERSION = re.compile(r'^version: .*$', re.M)
LOCKED_CORE = re.compile(r'(^  foresight_core:\n(?:    .*\n)*?    version: )"[^"]*"', re.M)


def read_version(root=ROOT):
    """Return (version, build_number) from the desktop pubspec."""
    match = SOURCE.search((Path(root) / PUBSPEC).read_text())
    if not match:
        raise ValueError(f'{PUBSPEC} must declare "version: X.Y.Z+N"')
    return match[1], int(match[2])


def dart_source(version, build):
    return ('// Generated by tools/app_version.py from apps/desktop/pubspec.yaml; do not edit.\n'
            f"const openForesightVersion = '{version}';\n"
            f'const openForesightBuildNumber = {build};\n')


def derived(root, version, build):
    """Return {relative path: expected contents} for every checked-in copy."""
    root = Path(root)
    core = CORE_VERSION.sub(f'version: {version}', (root / CORE_PUBSPEC).read_text(), count=1)
    lock, found = LOCKED_CORE.subn(rf'\g<1>"{version}"', (root / DESKTOP_LOCK).read_text())
    if not found:
        raise ValueError(f'{DESKTOP_LOCK} has no foresight_core entry')
    return {CORE_PUBSPEC: core, DESKTOP_LOCK: lock, DART_VERSION: dart_source(version, build)}


def stale(root=ROOT):
    """Return the checked-in copies that disagree with the desktop pubspec."""
    root = Path(root)
    expected = derived(root, *read_version(root))
    return sorted(path for path, text in expected.items()
                  if not (root / path).exists() or (root / path).read_text() != text)


def set_version(version, build=None, root=ROOT):
    root = Path(root)
    if not SEMVER.fullmatch(version):
        raise ValueError('Version must be X.Y.Z')
    _, current_build = read_version(root)
    build = current_build + 1 if build is None else build
    if build <= current_build:
        raise ValueError(f'Build number must be greater than {current_build}')
    # Compute every copy before writing any, so a failure leaves the tree untouched.
    files = {PUBSPEC: SOURCE.sub(f'version: {version}+{build}', (root / PUBSPEC).read_text(), count=1),
             **derived(root, version, build)}
    for path, text in files.items():
        (root / path).write_text(text)
    return version, build


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--set', metavar='X.Y.Z', help='set the release version and bump the build number')
    action.add_argument('--check', action='store_true', help='fail if a derived copy is out of date')
    action.add_argument('--build-number', action='store_true', help='print the build number instead')
    parser.add_argument('--build', type=int, help='explicit build number for --set')
    args = parser.parse_args()
    if args.build is not None and not args.set:
        parser.error('--build requires --set')
    if args.set:
        version, build = set_version(args.set, args.build)
        print(f'{version}+{build}')
    elif args.check:
        if paths := stale():
            sys.exit('Out of date with ' + PUBSPEC + ': ' + ', '.join(paths)
                     + '\nRun: python3 tools/app_version.py --set <version>')
    else:
        version, build = read_version()
        print(build if args.build_number else version)


if __name__ == '__main__':
    main()
