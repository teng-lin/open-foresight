#!/usr/bin/env python3
"""Keep the failure ledger in docs/testing.md generated from, and checked against, its data.

    .venv/bin/python -m tools.failure_ledger            # check; exit 1 on any problem
    .venv/bin/python -m tools.failure_ledger --write    # regenerate the table in docs/testing.md
    .venv/bin/python -m tools.failure_ledger --verify-commits   # also check that closing commits exist and are ordered
    .venv/bin/python -m tools.failure_ledger --base origin/main # also refuse entries deleted since REV

The data lives in tools/failure_ledger.json: one entry per unresolved failure
(class, owner, bounded next experiment, exit criterion, status) and one per
consequence (an aggregate job that fails because of other entries). The table in
docs/testing.md between the generated-table markers is rendered from it and the
check fails when the two differ. The rules this enforces:

- An owner is a named person or the explicit `unassigned` marker; an entry with
  neither fails, and an owner is never filled in on anyone's behalf.
- A class other than UNKNOWN needs cited evidence; UNKNOWN stays UNKNOWN until it
  has some, and a closed entry cannot be UNKNOWN.
- A successful rerun never closes an entry. Reruns may be recorded, and change
  nothing. Closing needs a controlling test that is registered in the repository
  (a Python test function or a Dart `test(`/`testWidgets(`, not a comment or a
  substring) and a pair of commits (failing before, passing after). The pair is
  the author's claim: nothing runs the test at either commit. `--verify-commits`
  checks only that both are commits of this repository and are in order, and it
  is off by default. `--base REV` compares with the ledger at REV and refuses an
  entry that was deleted instead of closed; without it a deleted entry is a
  silent close that only review catches.
- A mitigated entry says what was mitigated; an open or mitigated entry has no
  closing record.
- A consequence names existing failure entries as causes, is consequence-only
  while any cause is not closed, and may be closed only when every cause is.

The data file and the document are inputs to be distrusted: both are read with a
size cap, JSON objects with a repeated key are refused, every field has a type and
a length limit, unknown fields are refused, and every message quotes only a
validated entry id or text with control characters escaped.

Exit status: 0 consistent, 1 problems, 2 an input could not be read.
"""

from __future__ import annotations

import argparse
from collections import Counter
from collections.abc import Mapping, Sequence
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import unicodedata
from typing import Any

from tools import boundary_inventory

ROOT = Path(__file__).resolve().parents[1]
DATA = "tools/failure_ledger.json"
DOCUMENT = "docs/testing.md"
SCHEMA = 1
MAX_DATA_BYTES = 256 * 1024
MAX_DOCUMENT_BYTES = 2 * 1024 * 1024
MAX_ENTRIES = 100
MAX_TEXT = 4000
MAX_LIST = 50
BEGIN = "<!-- failure-ledger:begin (generated by tools/failure_ledger.py from tools/failure_ledger.json; edit the data, not the table) -->"
END = "<!-- failure-ledger:end -->"
UNASSIGNED = "unassigned: needs named owner"
CLASSES = ("product", "fixture", "environment", "dependency", "artifact", "UNKNOWN")
STATUSES = ("open", "mitigated", "closed", "consequence-only")
OWNER_STATUSES = ("assigned", "unassigned", "not-applicable")
IDENTIFIER = re.compile(r"[A-Z][A-Z0-9]{0,3}[0-9]{1,3}")
COMMIT = re.compile(r"[0-9a-f]{40}")
HEADER = ("ID", "First job", "Class", "Exact error", "Owner", "Next bounded experiment", "Exit criterion (controlling test)", "Status")
COMMON = {"id", "kind", "first_job", "error", "owner", "owner_status", "next_experiment", "exit_criterion", "status", "status_note"}
FAILURE_FIELDS = COMMON | {"class", "class_note", "class_evidence", "reruns", "closed_by"}
CONSEQUENCE_FIELDS = COMMON | {"causes"}
DISPLAY_STATUS = {"consequence-only": "consequence only"}


def safe(value: Any, limit: int = 80) -> str:
    """Text for a message: printable ASCII only, anything else escaped, bounded."""
    text = value if isinstance(value, str) else repr(value)
    escaped = "".join(
        "\\\\" if char == "\\" else char if " " <= char <= "~" else f"\\x{ord(char):02x}" if ord(char) < 0x100 else f"\\u{ord(char):04x}"
        for char in text[: limit * 4]
    )
    return escaped if len(escaped) <= limit else escaped[:limit] + "..."


def _no_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    repeated = sorted(key for key, count in Counter(key for key, _value in pairs).items() if count > 1)
    if repeated:
        raise ValueError("a JSON object repeats the key " + ", ".join(safe(key, 40) for key in repeated))
    return dict(pairs)


def read_bounded(path: Path, limit: int) -> str:
    """The text of a regular file no larger than [limit] bytes; ValueError otherwise."""
    try:
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"{safe(path.name)} is not a regular file")
        with path.open("rb") as stream:
            data = stream.read(limit + 1)
    except OSError as error:
        raise ValueError(f"{safe(path.name)} cannot be read ({type(error).__name__})") from error
    if len(data) > limit:
        raise ValueError(f"{safe(path.name)} is larger than {limit} bytes")
    try:
        return data.decode()
    except UnicodeDecodeError as error:
        raise ValueError(f"{safe(path.name)} is not UTF-8") from error


def load(root: Path = ROOT) -> dict[str, Any]:
    text = read_bounded(root / DATA, MAX_DATA_BYTES)
    try:
        ledger = json.loads(text, object_pairs_hook=_no_duplicates)
    except RecursionError as error:
        raise ValueError(f"{DATA} is nested too deeply") from error
    except ValueError as error:
        reason = str(error) if str(error).startswith("a JSON object repeats") else f"not valid JSON ({type(error).__name__})"
        raise ValueError(f"{DATA}: {reason}") from error
    if not isinstance(ledger, dict):
        raise ValueError(f"{DATA} is not a JSON object")
    return ledger


MARKER_TEXT = ("failure-ledger:", "<!--", "-->")


def unsafe_text(value: str) -> str | None:
    """Why [value] may not appear in the document, or None.

    Control, format (bidirectional and zero-width) and separator characters are
    refused, and so is anything that could open or close a comment: a field must
    not be able to end the generated block or hide the rest of the page.
    """
    if any(unicodedata.category(char) in ("Cc", "Cf", "Zl", "Zp", "Cs", "Co") for char in value):
        return "contains control, bidirectional or zero-width characters"
    if any(marker in value for marker in MARKER_TEXT):
        return "contains a comment marker or failure-ledger: text"
    return None


def _text(entry: Mapping[str, Any], field: str, problems: list[str], where: str, *, required: bool = True) -> str | None:
    value = entry.get(field)
    if value is None and not required:
        return None
    if not isinstance(value, str) or not value.strip():
        problems.append(f"{where}: {field} must be non-empty text")
        return None
    if len(value) > MAX_TEXT:
        problems.append(f"{where}: {field} is longer than {MAX_TEXT} characters")
        return None
    reason = unsafe_text(value)
    if reason:
        problems.append(f"{where}: {field} {reason}")
        return None
    return value


def _texts(entry: Mapping[str, Any], field: str, problems: list[str], where: str) -> list[str]:
    value = entry.get(field)
    if not isinstance(value, list) or len(value) > MAX_LIST or not all(isinstance(item, str) and item.strip() and len(item) <= MAX_TEXT for item in value):
        problems.append(f"{where}: {field} must be a short list of non-empty text")
        return []
    if any(unsafe_text(item) for item in value):
        problems.append(f"{where}: {field} contains control characters or a comment marker")
        return []
    return list(value)


def _closing(entry: Mapping[str, Any], problems: list[str], where: str, root: Path) -> None:
    closed_by = entry.get("closed_by")
    if not isinstance(closed_by, dict) or set(closed_by) != {"test", "failing_before", "passing_after"}:
        problems.append(f"{where}: a closed entry needs closed_by with a test, failing_before and passing_after (a rerun closes nothing)")
        return
    test, before, after = closed_by["test"], closed_by["failing_before"], closed_by["passing_after"]
    if not isinstance(test, str) or len(test) > MAX_TEXT or "::" not in test or not all(part.strip() for part in test.split("::", 1)) or unsafe_text(test):
        problems.append(f"{where}: closed_by.test must be 'path/to/test_file::test name' (short, with no control characters)")
    else:
        path_text, name = test.split("::", 1)
        candidate = root / path_text
        try:
            inside = candidate.resolve().is_relative_to(root.resolve())
        except (OSError, ValueError, RuntimeError):  # a NUL, an overlong name or a symlink loop
            inside = False
        if not inside or ".." in Path(path_text).parts or Path(path_text).is_absolute():
            problems.append(f"{where}: closed_by.test must name a file inside the repository")
        else:
            try:
                read_bounded(candidate, MAX_DOCUMENT_BYTES)  # the link itself, so a symlink or a huge file is refused
            except ValueError:
                problems.append(f"{where}: the controlling test file {safe(path_text)} does not exist or cannot be read")
            else:
                try:
                    registered = boundary_inventory.is_registered(root, path_text, name)
                except Exception:  # noqa: BLE001 - a file that cannot be parsed registers nothing
                    registered = False
                if not registered:
                    problems.append(f"{where}: {safe(name)} is not a registered test in {safe(path_text)} (a .py test function or a Dart test, not a comment or a substring)")
    for label, sha in (("failing_before", before), ("passing_after", after)):
        if not isinstance(sha, str) or not COMMIT.fullmatch(sha):
            problems.append(f"{where}: closed_by.{label} must be a full lowercase commit hash")
    if isinstance(before, str) and before == after:
        problems.append(f"{where}: closed_by.failing_before and passing_after must be different commits")


def _reruns(entry: Mapping[str, Any], problems: list[str], where: str) -> None:
    reruns = entry.get("reruns", [])
    if not isinstance(reruns, list) or len(reruns) > MAX_LIST:
        problems.append(f"{where}: reruns must be a short list")
        return
    for rerun in reruns:
        if not isinstance(rerun, dict) or set(rerun) != {"result", "ref"} or rerun["result"] not in ("passed", "failed") or not isinstance(rerun["ref"], str) or not rerun["ref"].strip() or len(rerun["ref"]) > MAX_TEXT:
            problems.append(f"{where}: each rerun needs a result (passed or failed) and a ref")
            return


def _failure(entry: Mapping[str, Any], problems: list[str], where: str) -> None:
    klass = entry.get("class")
    if klass not in CLASSES:
        problems.append(f"{where}: class must be one of {', '.join(CLASSES)}")
    elif klass != "UNKNOWN":
        if not entry.get("class_evidence"):
            problems.append(f"{where}: class {klass} needs class_evidence; the class stays UNKNOWN until evidence is cited")
        else:
            _texts(entry, "class_evidence", problems, where)
    elif entry.get("class_evidence"):
        problems.append(f"{where}: class_evidence is cited but the class is UNKNOWN; set the class the evidence supports")
    if "class_note" in entry:
        _text(entry, "class_note", problems, where)
    _reruns(entry, problems, where)
    if entry.get("status") == "consequence-only":
        problems.append(f"{where}: a failure is open, mitigated or closed, not consequence-only")
    if entry.get("owner_status") == "not-applicable":
        problems.append(f"{where}: only a consequence can have owner_status not-applicable")


def _consequence(entry: Mapping[str, Any], problems: list[str], where: str, by_id: Mapping[str, Mapping[str, Any]]) -> None:
    causes = entry.get("causes")
    if not isinstance(causes, list) or not causes or len(causes) > MAX_LIST or not all(isinstance(cause, str) for cause in causes):
        problems.append(f"{where}: a consequence needs causes, a list of failure entry ids")
        return
    found = []
    for cause in causes:
        target = by_id.get(cause)
        if target is None:
            problems.append(f"{where}: cause {safe(cause, 20)} is not an entry")
        elif target.get("kind") != "failure":
            problems.append(f"{where}: cause {safe(cause, 20)} is not a failure entry")
        else:
            found.append(target)
    if len(found) != len(causes):
        return
    open_causes = [cause for cause in found if cause.get("status") != "closed"]
    if entry.get("status") == "consequence-only" and not open_causes:
        problems.append(f"{where}: every cause is closed, so this consequence is stale; close it")
    if entry.get("status") == "closed" and open_causes:
        problems.append(f"{where}: closed while {safe(open_causes[0].get('id'), 20)} is not closed; a green aggregate closes nothing")
    if entry.get("status") not in ("consequence-only", "closed"):
        problems.append(f"{where}: a consequence is consequence-only or closed")
    if entry.get("owner") is not None or entry.get("owner_status") != "not-applicable":
        problems.append(f"{where}: a consequence has no owner (owner null, owner_status not-applicable)")


def validate(ledger: Mapping[str, Any], root: Path = ROOT) -> list[str]:
    """Every rule violated by [ledger]; an empty list means the data is consistent."""
    problems: list[str] = []
    if ledger.get("schema") != SCHEMA:
        problems.append(f"{DATA}: schema must be {SCHEMA}")
    if set(ledger) - {"schema", "source", "entries"}:
        problems.append(f"{DATA}: unknown top-level fields " + ", ".join(safe(key, 30) for key in sorted(set(ledger) - {"schema", "source", "entries"})))
    source = ledger.get("source")
    if not isinstance(source, str) or not source.strip() or len(source) > MAX_TEXT:
        problems.append(f"{DATA}: source must name the run or issue the entries come from")
    entries = ledger.get("entries")
    if not isinstance(entries, list) or not entries:
        return [*problems, f"{DATA}: entries must be a non-empty list"]
    if len(entries) > MAX_ENTRIES:
        return [*problems, f"{DATA}: more than {MAX_ENTRIES} entries"]
    by_id: dict[str, Mapping[str, Any]] = {}
    for position, entry in enumerate(entries):
        identifier = entry.get("id") if isinstance(entry, dict) else None
        if not isinstance(entry, dict) or not isinstance(identifier, str) or not IDENTIFIER.fullmatch(identifier):
            problems.append(f"entry {position}: id must look like L1")
            continue
        if identifier in by_id:
            problems.append(f"{identifier}: the id is used twice")
            continue
        by_id[identifier] = entry
    for identifier, entry in by_id.items():
        where = identifier
        kind = entry.get("kind")
        if kind not in ("failure", "consequence"):
            problems.append(f"{where}: kind must be failure or consequence")
            continue
        unknown = sorted(set(entry) - (FAILURE_FIELDS if kind == "failure" else CONSEQUENCE_FIELDS))
        if unknown:
            problems.append(f"{where}: unknown fields " + ", ".join(safe(key, 30) for key in unknown))
        for field in ("first_job", "error", "next_experiment", "exit_criterion"):
            _text(entry, field, problems, where)
        status = entry.get("status")
        if status not in STATUSES:
            problems.append(f"{where}: status must be one of {', '.join(STATUSES)}")
        if "status_note" in entry and entry["status_note"] != "":
            _text(entry, "status_note", problems, where)
        _owner(entry, problems, where)
        if kind == "failure":
            _failure(entry, problems, where)
            if "causes" in entry:
                problems.append(f"{where}: only a consequence has causes")
            _status(entry, problems, where, root)
        else:
            _consequence(entry, problems, where, by_id)
    return problems


def _owner(entry: Mapping[str, Any], problems: list[str], where: str) -> None:
    owner, state = entry.get("owner"), entry.get("owner_status")
    if state not in OWNER_STATUSES:
        problems.append(f"{where}: owner_status must be assigned, unassigned or not-applicable; an entry with no owner must say unassigned")
    elif state == "assigned":
        if not isinstance(owner, str) or not owner.strip() or len(owner) > 200 or owner.strip().lower().startswith("unassigned") or unsafe_text(owner):
            problems.append(f"{where}: an assigned owner must be a name, not blank, 'unassigned', or text with control characters or comment markers")
    elif owner is not None:
        problems.append(f"{where}: owner must be null when owner_status is {state}")


def _status(entry: Mapping[str, Any], problems: list[str], where: str, root: Path) -> None:
    status = entry.get("status")
    note = entry.get("status_note")
    if status == "mitigated" and not (isinstance(note, str) and note.strip()):
        problems.append(f"{where}: a mitigated entry must say in status_note what was mitigated and what is not explained")
    if status == "closed":
        if entry.get("class") == "UNKNOWN":
            problems.append(f"{where}: a closed entry cannot be UNKNOWN; a closed cause has been shown")
        _closing(entry, problems, where, root)
    elif "closed_by" in entry:
        problems.append(f"{where}: closed_by is only for a closed entry")


def render_cell(value: str) -> str:
    """One table cell: a single line in which no pipe can split the row.

    A pipe is written `\\|`. Backslashes that come right before a pipe would turn
    that escape into `\\\\|`, which a Markdown table reads as a split, so each is
    written as the character reference `&#92;` first.
    """
    text = " ".join(value.split())
    text = re.sub(r"\\+(?=\|)", lambda run: "&#92;" * len(run.group(0)), text)
    return text.replace("|", "\\|")


def render_row(entry: Mapping[str, Any]) -> list[str]:
    klass = "consequence" if entry["kind"] == "consequence" else entry["class"] + (f" ({entry['class_note']})" if entry.get("class_note") else "")
    owner = {"unassigned": UNASSIGNED, "not-applicable": "not applicable"}.get(entry["owner_status"]) or entry["owner"]
    label = DISPLAY_STATUS.get(entry["status"], entry["status"])
    status = label + (f": {entry['status_note']}" if entry.get("status_note") else "")
    return [
        entry["id"], entry["first_job"], klass, entry["error"], owner, entry["next_experiment"], entry["exit_criterion"], status,
    ]


def render_table(ledger: Mapping[str, Any]) -> str:
    lines = ["| " + " | ".join(HEADER) + " |", "| " + " | ".join("---" for _ in HEADER) + " |"]
    lines += ["| " + " | ".join(render_cell(str(cell)) for cell in render_row(entry)) + " |" for entry in ledger["entries"]]
    return "\n".join(lines)


def extract_table(document: str) -> str | None:
    """The generated block of [document] between the markers, or None unless there is exactly one well-formed block."""
    if document.count(BEGIN) != 1 or document.count(END) != 1 or document.index(BEGIN) > document.index(END):
        return None
    return document[document.index(BEGIN) + len(BEGIN) : document.index(END)].strip("\n")


def replace_table(document: str, table: str) -> str:
    if extract_table(document) is None:
        raise ValueError(f"{DOCUMENT} needs exactly one begin and one end marker for the generated ledger table")
    head, rest = document.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{table}\n{END}{tail}"


def _git(root: Path, *arguments: str) -> int | None:
    """Exit status of a Git command in [root], or None if Git could not be run."""
    try:
        return subprocess.run(["git", "--no-replace-objects", "-C", str(root), *arguments], capture_output=True, timeout=30, check=False).returncode
    except (OSError, subprocess.SubprocessError):
        return None


def verify_commits(ledger: Mapping[str, Any], root: Path = ROOT) -> list[str]:
    """For each closed entry, independently: both commits exist and the failing one is an ancestor of the passing one.

    This checks the pair's existence and order and nothing more: it does not run the
    controlling test at either commit, so the pair stays the author's claim.
    """
    problems: list[str] = []
    for entry in ledger["entries"]:
        closed_by = entry.get("closed_by")
        if entry.get("status") != "closed" or not isinstance(closed_by, dict):
            continue
        missing = False
        for label in ("failing_before", "passing_after"):
            status = _git(root, "cat-file", "-e", f"{closed_by[label]}^{{commit}}")
            if status is None:
                return [*problems, "git could not be run to verify commits"]
            if status:
                problems.append(f"{entry['id']}: closed_by.{label} is not a commit in this repository")
                missing = True
        if missing:
            continue
        ordered = _git(root, "merge-base", "--is-ancestor", closed_by["failing_before"], closed_by["passing_after"])
        if ordered is None:
            return [*problems, "git could not be run to verify commits"]
        if ordered:
            problems.append(f"{entry['id']}: failing_before is not an ancestor of passing_after")
    return problems


def removed_entries(ledger: Mapping[str, Any], root: Path, base: str) -> list[str]:
    """Entries present in the ledger at [base] that are gone now: deleting an entry would be a silent close."""
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/@^~-]{0,200}", base) or base.startswith("-"):
        return [f"--base {safe(base)} is not a revision name"]
    try:
        result = subprocess.run(["git", "--no-replace-objects", "-C", str(root), "show", f"{base}:{DATA}"], capture_output=True, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        return ["git could not be run to compare with the base"]
    if result.returncode:
        return [f"{DATA} cannot be read at {safe(base)}"]
    if len(result.stdout) > MAX_DATA_BYTES:
        return [f"{DATA} at {safe(base)} is larger than {MAX_DATA_BYTES} bytes"]
    try:
        earlier = json.loads(result.stdout.decode(), object_pairs_hook=_no_duplicates)
        before = {entry["id"] for entry in earlier["entries"] if isinstance(entry, dict) and isinstance(entry.get("id"), str)}
    except (ValueError, KeyError, TypeError, RecursionError):
        return [f"{DATA} at {safe(base)} cannot be compared"]
    now = {entry.get("id") for entry in ledger["entries"] if isinstance(entry, dict)}
    return [f"{safe(identifier, 20)}: the entry exists at {safe(base)} and is gone; close it with a controlling test instead of deleting it" for identifier in sorted(before - now)]


def check(root: Path = ROOT, commits: bool = False, base: str | None = None) -> dict[str, Any]:
    """Load, validate and compare the generated table; problems are messages with only validated or escaped text."""
    try:
        ledger = load(root)
    except ValueError as error:
        return {"problems": [str(error)], "unreadable": True, "entries": 0}
    problems = validate(ledger, root)
    if problems:
        return {"problems": problems, "unreadable": False, "entries": len(ledger.get("entries") or ())}
    try:
        document = read_bounded(root / DOCUMENT, MAX_DOCUMENT_BYTES)
    except ValueError as error:
        return {"problems": [str(error)], "unreadable": True, "entries": len(ledger["entries"])}
    current = extract_table(document)
    if current is None:
        problems.append(f"{DOCUMENT}: needs exactly one begin and one end marker for the generated ledger table")
    elif current != render_table(ledger):
        problems.append(f"{DOCUMENT}: the ledger table differs from {DATA}; run python -m tools.failure_ledger --write")
    if commits:
        problems.extend(verify_commits(ledger, root))
    if base is not None:
        problems.extend(removed_entries(ledger, root, base))
    return {"problems": problems, "unreadable": False, "entries": len(ledger["entries"])}


class LedgerProblems(ValueError):
    """The data breaks the ledger's rules; carries every message."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("; ".join(problems[:3]))
        self.problems = problems


def write(root: Path = ROOT) -> Path:
    """Regenerate the table in the document, atomically; refuses while the data has problems.

    The new text is written to a temporary file in the same directory and renamed
    over the document, and a symbolic link at the document's path is refused.
    """
    ledger = load(root)
    problems = validate(ledger, root)
    if problems:
        raise LedgerProblems(problems)
    path = root / DOCUMENT
    if path.is_symlink():
        raise ValueError(f"{DOCUMENT} is a symbolic link")
    table = render_table(ledger)
    updated = replace_table(read_bounded(path, MAX_DOCUMENT_BYTES), table)
    if extract_table(updated) != table:
        raise ValueError(f"the regenerated {DOCUMENT} would not contain exactly the generated table; nothing was written")
    descriptor, temporary = tempfile.mkstemp(prefix=".testing-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as stream:
            stream.write(updated)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, path.stat().st_mode & 0o777)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    return path


def main(argv: Sequence[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter, allow_abbrev=False)
    parser.add_argument("--write", action="store_true", help="regenerate the table in docs/testing.md")
    parser.add_argument("--verify-commits", action="store_true", help="also check that the closing commits exist and are ordered (the test is not run)")
    parser.add_argument("--base", metavar="REV", help="also refuse an entry present in the ledger at REV that is now gone")
    arguments = parser.parse_args(sys.argv[1:] if argv is None else argv)
    if arguments.write:
        try:
            print(f"wrote {write(root).relative_to(root)}")
        except LedgerProblems as error:
            for problem in error.problems:
                print(f"- {problem}", file=sys.stderr)
            return 1
        except (ValueError, OSError) as error:
            print(f"failure_ledger: {safe(str(error), 400)}", file=sys.stderr)
            return 2
    report = check(root, arguments.verify_commits, arguments.base)
    for problem in report["problems"]:
        print(f"- {problem}", file=sys.stderr)
    if not report["problems"]:
        print(f"Failure ledger is consistent: {report['entries']} entries.")
    return 2 if report["unreadable"] else 1 if report["problems"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
